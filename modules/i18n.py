"""
Translation engine for NovaKit Toolbox.
Supports zh-CN (Simplified Chinese), zh-TW (Traditional Chinese), en (English).

Usage:
    from modules.i18n import _, set_locale, get_locale, LOCALES

    set_locale('en')
    print(_("设置"))  # → "Settings"
    print(_("{n} 个文件", n=5))  # → "5 files"
"""

LOCALES = {
    'zh-CN': '简体中文',
    'zh-TW': '繁體中文',
    'en': 'English',
}

_current_locale = 'zh-CN'


def set_locale(locale):
    global _current_locale
    if locale in LOCALES:
        _current_locale = locale


def get_locale():
    return _current_locale


def _(text, **kwargs):
    """Translate text to the current locale. Falls back to the text itself (zh-CN)."""
    result = _TRANSLATIONS.get(_current_locale, {}).get(text, text)
    if kwargs:
        try:
            result = result.format(**kwargs)
        except (KeyError, ValueError):
            pass
    return result


